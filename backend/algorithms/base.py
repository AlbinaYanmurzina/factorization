"""
backend/algorithms/base.py

Базовый абстрактный класс для всех алгоритмов факторизации.

Определяет единый интерфейс и механизм логирования для всех алгоритмов,
реализующих методы из учебного пособия (главы 3 и 6).

Паттерн проектирования: Template Method
- Определяет скелет алгоритма (метод factorize)
- Подклассы реализуют конкретные шаги
- Единый механизм логирования для всех алгоритмов
"""

from abc import ABC, abstractmethod
from typing import List, Dict, Any

class FactorizationAlgorithm(ABC):
    """
    Абстрактный базовый класс для алгоритмов факторизации.
    
    Все алгоритмы факторизации должны наследоваться от этого класса
    и реализовывать метод factorize().
    
    Attributes:
        steps_log (List[Dict[str, Any]]): Лог шагов работы алгоритма.
                                          Каждый элемент - словарь с полями:
                                          - "step": название шага
                                          - "details": детали шага
    
    Методы:
        factorize(n): Абстрактный метод для факторизации числа n
        log_step(step_name, details): Сохранение информации о шаге
        clear_logs(): Очистка лога перед новым запуском
    """
    
    def __init__(self):
        """
        Инициализация алгоритма.
        
        Создаёт пустой лог шагов. Лог очищается при каждом новом запуске
        через метод clear_logs() в начале factorize().
        """
        self.steps_log: List[Dict[str, Any]] = []

    def log_step(self, step_name: str, details: Any):
        """
        Сохранение информации о шаге работы алгоритма.
        
        Этот метод вызывается алгоритмом на каждом значимом шаге для
        документирования процесса факторизации. Данные используются
        frontend для пошаговой визуализации и обучения.
        
        Args:
            step_name (str): Название шага (например, "Инициализация", "Итерация 5")
            details (Any): Детали шага. Обычно словарь с полями:
                          - "message" (str): Текстовое описание
                          - "table" (List[Dict]): Табличные данные для отображения
                          - "matrix_data" (List[List]): Матрицы для визуализации
                          - "FB" (List): Факторная база (для QS)
                          - Другие специфичные для алгоритма данные
        
        Пример использования:
            self.log_step("Инициализация метода Ферма", {
                "message": "Начинаем с x = ⌈√n⌉ = 33",
                "table": [{"x": 33, "w": 16, "√w": 4}]
            })
        """
        self.steps_log.append({
            "step": step_name,
            "details": details
        })

    def clear_logs(self):
        """
        Очистка лога шагов.
        
        Должна вызываться в начале метода factorize() для очистки
        лога от предыдущих запусков. Это гарантирует, что каждый
        вызов factorize() начинается с чистого лога.
        """
        self.steps_log = []

