"""
backend/algorithms/fermat.py

Метод факторизации Ферма (раздел 3.1 учебного пособия).

Один из простейших алгоритмов факторизации, основанный на представлении
нечётного числа как разности квадратов: n = x² - y² = (x-y)(x+y)

Сложность: O(|p-q|/2), где p и q - делители числа n
Память: O(1)

Эффективность:
- Отлично работает когда делители близки к √n (p ≈ q)
- Катастрофически медленен когда один делитель мал (p ≪ q)

Исторический контекст:
Метод Ферма является "дедушкой" квадратичного решета. Именно его недостаток
(медленная работа при далёких делителях) привёл к созданию более эффективных
методов, использующих множество соотношений вместо одного.
"""

import math
from typing import List
from .base import FactorizationAlgorithm
from .math_utils import is_prime


class FermatFactorization(FactorizationAlgorithm):
    """
    Метод факторизации Ферма (раздел 3.1 учебного пособия).

    Идея: любое нечётное n можно представить как n = x² − y² = (x−y)(x+y).
    Ищем x ≥ ⌈√n⌉ такое, что w = x² − n является полным квадратом.
    Тогда p = x − √w, q = x + √w.

    Работает мгновенно, если делители близки к √n (|p − q| мало).
    Катастрофически медленен, если один делитель мал (тогда x ≈ n/2).
    
    Attributes:
        steps_log: Лог шагов работы алгоритма (наследуется от базового класса)
    """

    def __init__(self):
        """Инициализация алгоритма Ферма."""
        super().__init__()

    def _isqrt_exact(self, w: int):
        """
        Проверка, является ли w полным квадратом.
        
        Args:
            w (int): Проверяемое число
        
        Returns:
            int | None: √w если w — полный квадрат, иначе None
        
        Примечание:
            Использует math.isqrt() для вычисления целой части корня,
            затем проверяет равенство s² = w
        """
        if w < 0:
            return None
        s = math.isqrt(w)
        if s * s == w:
            return s
        return None

    def _fermat_step(self, n: int):
        """
        Один проход метода Ферма для числа n.
        
        Алгоритм:
        1. Начинаем с x = ⌈√n⌉
        2. Для каждого x вычисляем w = x² - n
        3. Проверяем, является ли w полным квадратом
        4. Если да - нашли разложение n = (x-√w)(x+√w)
        5. Если нет - увеличиваем x и повторяем
        
        Args:
            n (int): Число для факторизации (нечётное, n > 1)
        
        Returns:
            int: Нетривиальный делитель n, или n если разложение не найдено
        
        Примечание:
            Метод логирует все итерации для образовательных целей.
            Для больших чисел с далёкими делителями может работать очень долго.
        """
        # Тривиальный случай: чётное число
        if n % 2 == 0:
            self.log_step("Тривиальный делитель", {
                "message": f"{n} чётное → делитель = 2"
            })
            return 2

        # Вычисляем начальное значение x = ⌈√n⌉
        x = math.isqrt(n)
        if x * x < n:
            x += 1  # x = ⌈√n⌉

        self.log_step("Инициализация метода Ферма", {
            "message": (
                f"Число n = {n}\n"
                f"Идея: ищем x, y такие что n = x² − y² = (x−y)(x+y).\n"
                f"Тогда делители: p = x − y, q = x + y.\n"
                f"Начинаем с x = ⌈√{n}⌉ = {x}.\n"
                f"На каждом шаге проверяем: является ли w = x² − n полным квадратом.\n"
                f"Если да — нашли y = √w и делители."
            )
        })

        max_log_rows = 20
        table_data = []
        iteration = 0

        while x <= (n + 9) // 2:  # x не может превышать (n+1)/2
            w = x * x - n
            y_exact = self._isqrt_exact(w)
            iteration += 1

            is_perfect = y_exact is not None
            row = {
                "Итерация": iteration,
                "x": x,
                "w = x²−n": w,
                "√w": y_exact if is_perfect else f"≈{math.isqrt(w):.0f} (не целое)",
                "Полный квадрат?": "✓" if is_perfect else "✗",
            }

            if iteration <= max_log_rows or is_perfect:
                table_data.append(row)

            if is_perfect:
                y = y_exact
                p = x - y
                q = x + y

                self.log_step(
                    f"Итерации алгоритма (всего: {iteration})",
                    {
                        "message": (
                            f"Перебираем x = {math.isqrt(n) if math.isqrt(n)*math.isqrt(n) >= n else math.isqrt(n)+1}, "
                            f"{math.isqrt(n)+1 if math.isqrt(n)*math.isqrt(n) >= n else math.isqrt(n)+2}, ...\n"
                            f"Для каждого x вычисляем w = x² − n и проверяем, является ли w полным квадратом.\n"
                            f"Показаны первые {min(iteration, max_log_rows)} итераций + финальная."
                        ),
                        "table": table_data,
                    },
                )

                self.log_step("Найдено представление n = x² − y²", {
                    "message": (
                        f"На итерации {iteration}:\n"
                        f"  x = {x},  w = x² − n = {x}² − {n} = {w}\n"
                        f"  √w = {y} (целое число!) ✓\n"
                        f"  n = {x}² − {y}² = ({x}−{y})·({x}+{y})\n"
                        f"  p = x − y = {x} − {y} = {p}\n"
                        f"  q = x + y = {x} + {y} = {q}\n"
                        f"  Проверка: {p} × {q} = {p * q} {'= n ✓' if p * q == n else '≠ n ✗'}"
                    )
                })

                if p == 1:
                    # Нашли тривиальное разложение n = 1 × n
                    self.log_step("Тривиальное разложение", {
                        "message": (
                            f"p = 1, q = {q} — тривиальное разложение.\n"
                            f"Это означает, что n = {n} является простым числом\n"
                            f"(или алгоритм дошёл до x = (n+1)/2 без успеха)."
                        )
                    })
                    return n

                return p  # возвращаем меньший делитель

            x += 1

        # Дошли до конца — n простое
        self.log_step(f"Итерации алгоритма (всего: {iteration})", {
            "message": (
                f"Перебрали все x от ⌈√n⌉ до (n+1)/2.\n"
                f"Полный квадрат не найден → n простое."
            ),
            "table": table_data,
        })
        return n

    def factorize(self, n: int) -> List[int]:
        """
        Полная факторизация числа n методом Ферма.
        
        Рекурсивно разлагает n на простые множители, используя метод Ферма
        для поиска делителей составных чисел.
        
        Алгоритм:
        1. Обработка тривиальных случаев (n ≤ 1, чётные, простые)
        2. Для составных чисел: применяем _fermat_step
        3. Полученные делители рекурсивно факторизуем
        4. Собираем все простые множители
        
        Args:
            n (int): Число для факторизации (n > 0)
        
        Returns:
            List[int]: Отсортированный список простых множителей
        
        Примеры:
            factorize(15) → [3, 5]
            factorize(84) → [2, 2, 3, 7]
            factorize(143) → [11, 13]  # быстро, т.к. 11 и 13 близки к √143
            factorize(1000003) → [1000003]  # простое число
        
        Примечание:
            Для чисел с далёкими делителями (например, 2 × большое_простое)
            метод работает очень медленно. В таких случаях лучше использовать
            ρ-метод Полларда или квадратичное решето.
        """
        self.clear_logs()

        # Тривиальные случаи
        if n <= 1:
            return [n]
        if n % 2 == 0:
            return sorted([2, n // 2])
        if is_prime(n):
            self.log_step("Число простое", {
                "message": f"n = {n} — простое (тест Миллера–Рабина). Факторизация не требуется."
            })
            return [n]

        self.log_step("Запуск: Метод Ферма", {
            "message": (
                f"n = {n} ({n.bit_length()} бит)\n"
                f"Метод Ферма — «дедушка» квадратичного решета.\n"
                f"Основан на представлении n = x² − y² = (x−y)(x+y).\n"
                f"Сложность: O(|p−q|/2) итераций, где p, q — делители.\n"
                f"• Если p ≈ q (делители близки к √n) → работает мгновенно.\n"
                f"• Если p ≪ q (один делитель мал) → катастрофически медленно.\n"
                f"Именно этот недостаток привёл к созданию квадратичного решета."
            )
        })

        # Стек для рекурсивной факторизации
        factors = []
        stack = [n]

        while stack:
            current = stack.pop()

            if current <= 1:
                continue

            # Проверка на простоту
            if is_prime(current):
                factors.append(current)
                self.log_step("Простое число найдено", {
                    "message": f"{current} — простое (тест Миллера–Рабина). Добавляем в результат."
                })
                continue

            # Составное число — применяем метод Ферма
            self.log_step("Составное число", {
                "message": f"{current} — составное. Запускаем метод Ферма."
            })

            divisor = self._fermat_step(current)

            if divisor == current:
                # Не удалось разложить (не должно случиться для составных, но на всякий случай)
                factors.append(current)
            else:
                quotient = current // divisor
                self.log_step("Разбиение числа", {
                    "message": (
                        f"{current} = {divisor} × {quotient}\n"
                        f"Оба числа отправляются на дальнейшую проверку."
                    )
                })
                # Добавляем оба делителя в стек для дальнейшей факторизации
                stack.append(divisor)
                stack.append(quotient)

        factors.sort()
        self.log_step("Факторизация завершена", {
            "message": f"Итоговое разложение: {n} = {' × '.join(map(str, factors))}"
        })
        return factors
