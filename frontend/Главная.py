with st.expander("🔗 CFRAC — факторизация непрерывными дробями", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Исторически** — первый субэкспоненциальный алгоритм факторизации (Morrison & Brillhart, 1975).

**Идея.** Разложение √n в непрерывную дробь даёт подходящие дроби A_k/B_k,
для которых выполняется соотношение:
        """)
        st.latex(r"A_k^2 \equiv (-1)^k \cdot d_k \pmod{n}, \quad |d_k| < 2\sqrt{n}")
        st.markdown("""
Если d_k раскладывается по факторной базе — получаем соотношение.

**Рекуррентность цепной дроби:**
        """)
        st.latex(r"m_{k+1} = d_k \cdot a_k - m_k")
        st.latex(r"d_{k+1} = \frac{n - m_{k+1}^2}{d_k}")
        st.latex(r"a_{k+1} = \left\lfloor\frac{a_0 + m_{k+1}}{d_{k+1}}\right\rfloor")
        st.markdown("""
**Шаги алгоритма:**
1. Построить факторную базу FB = {−1} ∪ {p ≤ B : (n/p) = 1}
2. Итерировать цепную дробь, проверяя d_k на B-гладкость
3. Набрать |FB| + extra соотношений
4. Гаусс над GF(2) → линейные зависимости
5. Для каждой зависимости: X = ∏A_k, Y = √(∏|d_k|), проверить НОД(X−Y, n)
        """)
    with c2:
        st.latex(r"\sqrt{n} = a_0 + \cfrac{1}{a_1 + \cfrac{1}{a_2 + \cdots}}")
        st.latex(r"\gcd(X - Y,\; n)")
        st.caption("Отличие от QS: числа берутся из цепной дроби, а не из полинома x²−n")

with st.expander("⚙️ Квадратичное решето — базовый алгоритм (Диксона)", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея Диксона.** Ищем x, y такие что x² ≡ y² (mod n).
Тогда НОД(x−y, n) с вероятностью 1/2 даёт нетривиальный делитель.

**Полином просеивания:**
        """)
        st.latex(r"Q(x) = x^2 - n, \quad x = \lceil\sqrt{n}\rceil, \lceil\sqrt{n}\rceil+1, \ldots")
        st.markdown("""
Q(x) мало по модулю (≈ 2x·Δ), поэтому шансы на гладкость высоки.

**Факторная база:** простые p ≤ B, для которых (n/p) = 1 (символ Лежандра).

**Шаги алгоритма:**
1. Выбрать B по формуле L-нотации: B ≈ exp(0.5·√(ln n · ln ln n))
2. Построить факторную базу FB
3. Перебирать x, проверять Q(x) на B-гладкость пробным делением
4. Набрать |FB| + 5 гладких чисел
5. Составить матрицу показателей степеней mod 2
6. Гаусс над GF(2) → зависимости → НОД(X−Y, n)

**Недостаток:** поиск гладких — пробным делением, O(M · |FB|).
        """)
    with c2:
        st.latex(r"B \approx \exp\!\left(0.5\sqrt{\ln n \cdot \ln\ln n}\right)")
        st.latex(r"\left(\frac{n}{p}\right) = 1")
        st.latex(r"Ax = 0 \pmod{2}")
        st.caption("Гаусс над GF(2) находит подмножество с квадратным произведением")

with st.expander("⚡ Квадратичное решето — оптимизированный (логарифмическое просеивание)", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Улучшение 1: алгоритм Тонелли–Шенкса.**
Для каждого p из FB заранее вычисляем корни r₁, r₂: r² ≡ n (mod p).
Это задаёт стартовые позиции просеивания.

**Улучшение 2: логарифмическое просеивание.**
Вместо пробного деления каждого Q(x) на все p:
        """)
        st.latex(r"\text{sieve}[i] \mathrel{+}= \log_2 p \quad \text{для } i \equiv r_1, r_2 \pmod{p}")
        st.markdown("""
После просеивания: sieve[i] ≈ log₂(Q(x_i)) означает B-гладкость.

**Сложность просеивания:** O(M log log M) вместо O(M · |FB|).

**Шаги алгоритма:**
1. Построить FB с корнями (Тонелли–Шенкс)
2. Инициализировать массив sieve[0..M] нулями
3. Для каждого p: добавить log₂(p) в позиции r₁, r₁+p, r₁+2p, … и r₂, r₂+p, …
4. Кандидаты: i, где sieve[i] ≥ log₂(Q(x_i)) − допуск
5. Проверить кандидатов пробным делением
6. Гаусс → НОД
        """)
    with c2:
        st.latex(r"r^2 \equiv n \pmod{p}")
        st.latex(r"\text{sieve}[i] \approx \log_2 Q(x_i)")
        st.caption("Тонелли–Шенкс: O(log²p) на вычисление корня")

with st.expander("🤖 Квадратичное решето — AUTO (автоподбор параметров)", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Отличие от Optimized:** параметры B и M подбираются автоматически
по теоретической формуле L-нотации в зависимости от разрядности числа.
        """)
        st.latex(r"L(n,\tfrac{1}{2}) = \exp\!\left(\sqrt{\ln n \cdot \ln\ln n}\right)")
        st.latex(r"B = L(n,\tfrac{1}{2})^{\alpha}, \quad \alpha \in [0.15,\, 0.45]")
        st.markdown("""
Коэффициент α зависит от разрядности:
- < 35 бит: α = 0.15, M = 20 000
- 35–50 бит: α = 0.25, M = 60 000
- 50–70 бит: α = 0.35, M = 150 000
- > 70 бит: α = 0.45, M = 400 000

**Цель:** достичь теоретического оптимума QS без ручной настройки.
        """)
    with c2:
        st.latex(r"\alpha \approx \frac{1}{2} \Rightarrow \text{оптимум QS}")
        st.caption("Python медленнее C++, поэтому α < 0.5 для разумного времени")

with st.expander("🧩 Квадратичное решето — LPV (Large Prime Variation)", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея.** Принимать не только B-гладкие числа, но и **полугладкие** —
числа вида Q(x) = smooth_part × P, где P — один большой простой B < P < B².

**Склейка пар:** два полугладких с одинаковым P перемножаются:
        """)
        st.latex(r"Q(x_1) = s_1 \cdot P, \quad Q(x_2) = s_2 \cdot P")
        st.latex(r"Q(x_1) \cdot Q(x_2) = s_1 s_2 \cdot P^2 \quad \Rightarrow \text{полный квадрат по } P")
        st.markdown("""
**Эффект:** резко увеличивается количество используемых соотношений.
На практике LPV даёт ускорение в 2–4 раза по сравнению с базовым QS.

**Шаги алгоритма:**
1. Просеивание с расширенным допуском
2. Полностью гладкие → сразу в базу
3. Полугладкие → в словарь partials[P]
4. При совпадении P → склеить в одно соотношение
5. Гаусс → НОД
        """)
    with c2:
        st.latex(r"B < P < B^2")
        st.latex(r"\gcd(X - Y,\; n)")
        st.caption("Раздел 6.8 учебника")

with st.expander("🔀 Квадратичное решето — MPQS (Multiple Polynomial QS)", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея.** Вместо одного полинома Q(x) = x² − n использовать семейство полиномов:
        """)
        st.latex(r"Q(x) = ax^2 + 2bx + c, \quad a = t^2,\quad b^2 \equiv n \pmod{a}")
        st.markdown("""
Тогда a·Q(x) = (ax + b)² − n, и значения Q(x) малы на интервале [−M, M]:
        """)
        st.latex(r"|Q(x)| \approx \frac{M\sqrt{n}}{2} \ll x^2 - n")
        st.markdown("""
**Ключевой трюк:** X = ax + b (а не x), поскольку (ax+b)² = t²·Q(x) (mod n).

**Параметр a:** выбирается как t² ≈ √(2n/M), что минимизирует |Q(x)|.

**Шаги алгоритма:**
1. Выбрать t (простое), вычислить b через лемму Гензеля
2. Просеять полином на [−M, M]
3. Сменить t → новый полином, повторить до набора |FB|+5 соотношений
4. Гаусс → НОД

**Преимущество:** каждый полином даёт независимые соотношения,
значения Q(x) меньше → больше гладких чисел на единицу работы.
        """)
    with c2:
        st.latex(r"a = t^2 \approx \sqrt{\frac{2n}{M}}")
        st.latex(r"(ax+b)^2 \equiv t^2 Q(x) \pmod{n}")
        st.caption("Раздел 6.9 учебника. Монтгомери, 1994")

with st.expander("⚡ Квадратичное решето — MPQS Параллельный", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея.** Полиномы в MPQS полностью независимы друг от друга —
их просеивание можно распараллелить на все ядра CPU.

**Архитектура Master-Worker:**
- **Master** (главный процесс): генерирует t-значения, собирает результаты, запускает Гаусс
- **Workers** (N процессов): каждый просеивает свою пачку полиномов независимо

**Реализация:** `concurrent.futures.ProcessPoolExecutor`.
Данные передаются как кортежи `(p, log_p, sqrt_n)` — минимальный pickle-overhead.

**Оптимизация памяти:** `array.array('f')` вместо `list[float]` — в 8 раз меньше памяти на массив просеивания.

**Теоретическое ускорение:** линейное по числу ядер (при достаточном числе полиномов).
        """)
    with c2:
        st.latex(r"\text{Speedup} \approx N_{\text{cores}}")
        st.caption("ProcessPoolExecutor обходит GIL через отдельные процессы")

