"""
backend/algorithms/math_utils.py

Общие математические утилиты для алгоритмов факторизации.

Содержит базовые математические функции, используемые всеми алгоритмами:
- is_prime: Вероятностный тест простоты Миллера-Рабина
- generate_primes: Решето Эратосфена для генерации простых чисел
- legendre_symbol: Символ Лежандра для проверки квадратичных вычетов
- tonelli_shanks: Алгоритм Тонелли-Шенкса для извлечения квадратного корня mod p

Эти функции являются строительными блоками для реализации алгоритмов
из учебного пособия (главы 3 и 6).

Где используется каждая функция подробно описано в комментариях к ней.
"""

import random
import math
from typing import List, Optional


def is_prime(n: int, k: int = 5) -> bool:
    """
    Вероятностный тест простоты Миллера-Рабина.

    Используется повсеместно: в алгоритмах Ферма, Полларда (ρ и p-1),
    Уильямса (p+1), SQUFOF, CFRAC и всех вариантах квадратичного решета —
    чтобы проверить, является ли найденный делитель простым числом,
    а не составным.

    Параметры:
        n — проверяемое число
        k — количество раундов (больше k → меньше вероятность ошибки;
            вероятность ложно-положительного результата ≤ 4^(-k))

    Возвращает True, если n, вероятно, простое; False — если составное.
    """
    if n < 2: return False
    if n in (2, 3): return True
    if n % 2 == 0: return False

    # Представляем n - 1 как 2^s * d, где d — нечётное.
    # Это нужно для структуры теста: сначала проверяем a^d mod n,
    # затем последовательно возводим в квадрат s-1 раз.
    s, d = 0, n - 1
    while d % 2 == 0:
        s += 1
        d //= 2

    for _ in range(k):
        a = random.randint(2, n - 2)  # случайное основание
        x = pow(a, d, n)              # a^d mod n (быстрое возведение)

        # Если сразу получили 1 или n-1 — этот раунд пройден
        if x == 1 or x == n - 1:
            continue

        # Повторно возводим в квадрат; ищем n-1 (≡ -1 mod n)
        for _ in range(s - 1):
            x = pow(x, 2, n)
            if x == n - 1:
                break
        else:
            # Цикл завершился без break → свидетель составности найден
            return False

    return True  # все k раундов пройдены — число, вероятно, простое


def generate_primes(limit: int) -> List[int]:
    """
    Решето Эратосфена: генерирует все простые числа до limit включительно.

    Используется для построения факторной базы в:
      - quadratic_sieve_basic/optimized/lpv/mpqs/mpqs_parallel.py
        (простые числа, по которым гладкие числа раскладываются на множители)
      - cfrac.py (аналогичная факторная база для CFRAC)
      - pollard_p1.py, williams_p1.py
        (перебор простых степеней при вычислении произведения B-гладких чисел)

    Параметры:
        limit — верхняя граница (включительно)

    Возвращает отсортированный список простых чисел [2, 3, 5, ..., ≤ limit].
    """
    if limit < 2:
        return []

    # Булев массив: sieve[i] == True означает, что i — простое
    sieve = [True] * (limit + 1)
    sieve[0] = sieve[1] = False

    # Достаточно проверять делители до √limit
    for i in range(2, int(math.isqrt(limit)) + 1):
        if sieve[i]:
            # Зачёркиваем все кратные i, начиная с i²
            for j in range(i * i, limit + 1, i):
                sieve[j] = False

    return [i for i, is_p in enumerate(sieve) if is_p]


def legendre_symbol(a: int, p: int) -> int:
    """
    Символ Лежандра (a/p) — показывает, является ли 'a' квадратичным
    вычетом по простому модулю p.

    Используется в:
      - quadratic_sieve_basic/optimized/lpv/mpqs/mpqs_parallel.py
        (отбор простых из факторной базы: берём только те p, для которых
         n является квадратичным вычетом, т.е. x² ≡ n (mod p) имеет решение)
      - cfrac.py (аналогичный отбор для CFRAC)
      - tonelli_shanks() ниже (поиск квадратичного невычета z)

    Возвращает:
         1  — a является квадратичным вычетом mod p (x² ≡ a (mod p) решаемо)
        -1  — a является квадратичным невычетом mod p
         0  — a кратно p
    """
    if a % p == 0:
        return 0

    # Критерий Эйлера: (a/p) ≡ a^((p-1)/2) (mod p)
    ls = pow(a, (p - 1) // 2, p)

    # pow() в Python возвращает значение в [0, p-1].
    # Результат p-1 соответствует -1 mod p (квадратичный невычет).
    return -1 if ls == p - 1 else ls


def tonelli_shanks(n: int, p: int) -> Optional[int]:
    """
    Алгоритм Тонелли-Шенкса: находит x такое, что x² ≡ n (mod p).

    Используется в инициализации решета квадратичного решета:
      - quadratic_sieve_optimized/lpv/mpqs/mpqs_parallel.py
        (для каждого простого p из факторной базы находим стартовые позиции
         решета — индексы i, с которых Q(i) = (⌈√n⌉ + i)² - n делится на p)

    Параметры:
        n — число, квадратный корень которого ищем
        p — простой модуль

    Возвращает одно из двух решений x (второе будет p - x), либо None,
    если решений нет (n — квадратичный невычет mod p).
    """
    n = n % p

    # Тривиальные случаи
    if n == 0: return 0
    if p == 2: return n
    if legendre_symbol(n, p) != 1:
        return None  # решений нет

    # Частный случай: если p ≡ 3 (mod 4), корень вычисляется напрямую
    if p % 4 == 3:
        return pow(n, (p + 1) // 4, p)

    # Шаг 1: разложим p - 1 = Q * 2^S (Q — нечётное).
    # S — «глубина» двоичного подъёма в алгоритме.
    q = p - 1
    s = 0
    while q % 2 == 0:
        s += 1
        q //= 2

    # Шаг 2: ищем квадратичный невычет z mod p.
    # Примерно половина чисел являются невычетами, поэтому цикл быстрый.
    z = 2
    while legendre_symbol(z, p) != -1:
        z += 1

    # Шаг 3: инициализация переменных алгоритма
    m = s
    c = pow(z, q, p)       # c = z^Q mod p — вспомогательный элемент порядка 2^S
    t = pow(n, q, p)       # t = n^Q mod p — должен стремиться к 1
    r = pow(n, (q + 1) // 2, p)  # r — текущее приближение корня

    # Шаг 4: итеративный подъём — корректируем r, пока t не станет 1
    while t != 0 and t != 1:
        # Находим наименьшее i > 0, при котором t^(2^i) ≡ 1 (mod p)
        t2i = t
        i = 0
        for i in range(1, m):
            t2i = pow(t2i, 2, p)
            if t2i == 1:
                break

        # b = c^(2^(m-i-1)) mod p — корректирующий множитель
        b = pow(c, pow(2, m - i - 1), p)

        # Обновляем все переменные для следующей итерации
        m = i
        c = pow(b, 2, p)
        t = (t * c) % p
        r = (r * b) % p

    return r  # r² ≡ n (mod p)
