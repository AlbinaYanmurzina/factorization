with st.expander("📐 Малая теорема Ферма", expanded=False):
    st.markdown("""
**Формулировка:** Если p — простое число, а a не делится на p, то:
    """)
    st.latex(r"a^{p-1} \equiv 1 \pmod{p}")
    st.markdown("""
**Простыми словами:** При возведении числа a в степень (p−1) и делении на простое p, остаток всегда равен 1.

**Пример:** p = 7, a = 2
- 2⁶ = 64
- 64 mod 7 = 1 ✓

**Применение в факторизации:**
(p−1)-метод Полларда использует эту теорему: если (p−1) содержит только малые простые множители (гладкое число), то можно найти делитель p через вычисление a^M mod n, где M кратно (p−1).

**Следствие:** Если a^M ≡ 1 (mod p), то p | НОД(a^M − 1, n).
    """)

with st.expander("🎯 Гладкие числа", expanded=False):
    st.markdown("""
**Определение:** Число называется B-гладким, если все его простые делители не превосходят B.

**Примеры:**
- 12 = 2² · 3 является 3-гладким (все делители ≤ 3)
- 60 = 2² · 3 · 5 является 5-гладким (все делители ≤ 5)
- 77 = 7 · 11 НЕ является 7-гладким (есть делитель 11 > 7)

**Граница гладкости B:**
Для квадратичного решета выбирается по формуле:
    """)
    st.latex(r"B \approx \exp\!\left(0.5\sqrt{\ln n \cdot \ln\ln n}\right)")
    st.markdown("""
**Применение в факторизации:**
- **(p−1)-метод:** Ищет делители p, для которых (p−1) является B-гладким
- **Квадратичное решето:** Ищет числа Q(x) = x² − n, которые раскладываются только на простые из факторной базы (≤ B)

**Почему это важно?** Гладкие числа легко факторизуются, что позволяет строить соотношения вида x² ≡ y² (mod n).
    """)

with st.expander("🔍 Символ Лежандра", expanded=False):
    st.markdown("""
**Определение:** Для нечётного простого p и целого a символ Лежандра определяется как:
    """)
    st.latex(r"\left(\frac{a}{p}\right) = \begin{cases} 1, & \text{если } a \text{ — квадратичный вычет по модулю } p \\ -1, & \text{если } a \text{ — квадратичный невычет по модулю } p \\ 0, & \text{если } p \mid a \end{cases}")
    st.markdown("""
**Простыми словами:** Символ Лежандра показывает, существует ли такое x, что x² ≡ a (mod p).

**Пример:** p = 7
- (1/7) = 1, так как 1² ≡ 1 (mod 7)
- (2/7) = 1, так как 3² = 9 ≡ 2 (mod 7)
- (3/7) = −1, так как нет x: x² ≡ 3 (mod 7)
- (4/7) = 1, так как 2² ≡ 4 (mod 7)

**Применение в квадратичном решете:**
Факторная база FB состоит из простых p ≤ B, для которых (n/p) = 1. Это означает, что n является квадратичным вычетом по модулю p, т.е. существует решение уравнения x² ≡ n (mod p). Такие простые могут делить значения Q(x) = x² − n.

**Критерий Эйлера для вычисления:**
    """)
    st.latex(r"\left(\frac{a}{p}\right) \equiv a^{(p-1)/2} \pmod{p}")

with st.expander("🎲 Парадокс дней рождения", expanded=False):
    st.markdown("""
**Суть парадокса:** В группе из 23 человек вероятность того, что у двух людей совпадут дни рождения, превышает 50%.

**Общая формула:** Если случайно выбирать элементы из множества размера N, то с вероятностью ~50% повторение встретится примерно через √N попыток.

**Применение в ρ-методе Полларда:**
При вычислении последовательности x₀, x₁, x₂, ... по модулю неизвестного делителя p:
- Размер множества: p
- Ожидаемое число шагов до повторения: √p ≈ n^(1/4)

Алгоритм Флойда («черепаха и заяц») обнаруживает цикл без хранения всей последовательности:
- Черепаха: x_{i+1} = f(x_i)
- Заяц: y_{i+1} = f(f(y_i))
- Когда x = y, найден цикл

**Пример:** Для n = 91 с делителем p = 7, цикл возникает примерно через √7 ≈ 2.6 шагов.
    """)
    st.latex(r"\text{Ожидаемая длина цикла} \approx \sqrt{\pi p / 2}")

with st.expander("⚡ Быстрое возведение в степень", expanded=False):
    st.markdown("""
**Задача:** Вычислить a^n mod m эффективно (за O(log n) операций вместо O(n)).

**Метод:** Используем двоичное представление показателя степени.

**Алгоритм:**
1. Представить n в двоичной системе
2. Последовательно возводить в квадрат
3. Умножать на a, когда встречается 1 в двоичной записи

**Пример:** Вычислить 2¹³ mod 100
- 13 = 1101₂ = 8 + 4 + 1
- 2¹ = 2
- 2² = 4
- 2⁴ = 16
- 2⁸ = 256 mod 100 = 56

2¹³ = 2⁸ · 2⁴ · 2¹ = 56 · 16 · 2 mod 100
= (56 · 16) mod 100 · 2 mod 100
= 896 mod 100 · 2 mod 100
= 96 · 2 mod 100
= 192 mod 100
= 92

**Применение:** Используется в (p−1)-методе Полларда для вычисления a^M mod n, где M может быть очень большим.
    """)
    st.code("""
def pow_mod(a, n, m):
    result = 1
    base = a % m
    while n > 0:
        if n % 2 == 1:
            result = (result * base) % m
        base = (base * base) % m
        n //= 2
    return result
    """, language="python")

with st.expander("🔄 Алгоритм Флойда (черепаха и заяц)", expanded=False):
    st.markdown("""
**Задача:** Обнаружить цикл в последовательности без хранения всех элементов.

**Идея:** Использовать два указателя, движущихся с разной скоростью:
- Черепаха делает 1 шаг: x_{i+1} = f(x_i)
- Заяц делает 2 шага: y_{i+1} = f(f(y_i))

**Почему работает?** Если есть цикл длины L, то заяц «обгонит» черепаху внутри цикла, и они встретятся.

**Пример последовательности:** f(x) = (x² + 1) mod 13, x₀ = 2
- i=0: x=2, y=2
- i=1: x=5, y=12 (заяц: 2→5→12)
- i=2: x=12, y=2 (заяц: 12→2→5→12)
- i=3: x=2, y=12
- Цикл обнаружен!

**Применение в ρ-методе:** Когда x ≡ y (mod p), то p | НОД(|x−y|, n), что даёт делитель n.

**Преимущества:**
- Память: O(1) вместо O(√p)
- Простота реализации
- Гарантированное обнаружение цикла
    """)
    st.code("""
def floyd_cycle_detection(f, x0):
    tortoise = f(x0)
    hare = f(f(x0))
    
    while tortoise != hare:
        tortoise = f(tortoise)
        hare = f(f(hare))
    
    return tortoise  # точка встречи
    """, language="python")

with st.expander("📊 Факторная база", expanded=False):
    st.markdown("""
**Определение:** Факторная база (FB) — множество малых простых чисел, используемых для разложения в алгоритмах факторизации.

**Для квадратичного решета:**
FB состоит из простых p ≤ B, для которых (n/p) = 1 (символ Лежандра).

**Пример:** Для n = 143, B = 7
- Проверяем простые: 2, 3, 5, 7
- (143/2) = (1/2) = 1 ✓
- (143/3) = (2/3) = −1 ✗
- (143/5) = (3/5) = −1 ✗
- (143/7) = (3/7) = −1 ✗

FB = {2} (только 2 подходит)

**Размер факторной базы:** Обычно |FB| ≈ π(B), где π(B) — количество простых ≤ B.

**Применение:**
1. Ищем числа Q(x) = x² − n, которые раскладываются только на простые из FB
2. Для каждого гладкого Q(x) записываем вектор показателей степеней
3. Находим линейную зависимость над GF(2) → получаем x² ≡ y² (mod n)

**Почему это работает?** Чем больше FB, тем больше вероятность найти гладкие числа, но тем медленнее проверка на гладкость.
    """)
    st.latex(r"\text{FB} = \{p \text{ простое} : p \leq B \text{ и } (n/p) = 1\}")

