with st.expander("📉 (p−1)-метод Полларда — пример: n = 299, B = 5", expanded=False):
    st.markdown("**Задача:** разложить n = 299. Граница гладкости B = 5, основание a = 2.")
    
    st.markdown("**Решение:**")
    st.markdown("""
**Шаг 1. Построение списка простых чисел ≤ B:**
- Простые числа до 5: {2, 3, 5}
    """)
    
    st.markdown("**Шаг 2. Вычисление M (произведение степеней простых):**")
    st.markdown("""
Для каждого простого q ≤ B берём максимальную степень q^k ≤ B:
- Для q = 2: 2² = 4 ≤ 5, но 2³ = 8 > 5 → берём 2²
- Для q = 3: 3¹ = 3 ≤ 5, но 3² = 9 > 5 → берём 3¹
- Для q = 5: 5¹ = 5 ≤ 5, но 5² = 25 > 5 → берём 5¹

M = 2² · 3 · 5 = 4 · 3 · 5 = 60
    """)
    
    st.markdown("**Шаг 3. Вычисление a^M mod n:**")
    st.markdown("""
Нужно вычислить 2⁶⁰ mod 299. Используем быстрое возведение в степень:

60 = 32 + 16 + 8 + 4 = 2⁵ + 2⁴ + 2³ + 2²

Вычисляем степени двойки:
- 2¹ mod 299 = 2
- 2² mod 299 = 4
- 2⁴ mod 299 = 16
- 2⁸ mod 299 = 256
- 2¹⁶ mod 299 = 256² mod 299 = 65536 mod 299 = 136
- 2³² mod 299 = 136² mod 299 = 18496 mod 299 = 280

Теперь: 2⁶⁰ = 2³² · 2¹⁶ · 2⁸ · 2⁴
- 2⁶⁰ mod 299 = (280 · 136 · 256 · 16) mod 299

Вычисляем пошагово:
- 280 · 136 mod 299 = 38080 mod 299 = 85
- 85 · 256 mod 299 = 21760 mod 299 = 221
- 221 · 16 mod 299 = 3536 mod 299 = 285

Итого: 2⁶⁰ mod 299 = 285
    """)
    
    st.markdown("**Шаг 4. Вычисление НОД:**")
    st.markdown("""
d = НОД(2⁶⁰ − 1, 299) = НОД(285 − 1, 299) = НОД(284, 299)

Алгоритм Евклида:
- 299 = 1 · 284 + 15
- 284 = 18 · 15 + 14
- 15 = 1 · 14 + 1
- 14 = 14 · 1 + 0

НОД(284, 299) = 13
    """)
    
    st.markdown("**Шаг 5. Проверка:**")
    st.markdown("""
- 299 ÷ 13 = 23 ✓
- Проверяем: 13 · 23 = 299 ✓

**Почему сработало?**
- p = 13, тогда p − 1 = 12 = 2² · 3
- Все простые делители (p−1) не превосходят B = 5 → (p−1) является B-гладким
- По малой теореме Ферма: 2¹² ≡ 1 (mod 13)
- Так как M = 60 = 5 · 12, то 2⁶⁰ = (2¹²)⁵ ≡ 1⁵ = 1 (mod 13)
- Значит 13 | (2⁶⁰ − 1), поэтому НОД(2⁶⁰ − 1, 299) = 13

**Ответ:** 299 = 13 × 23
    """)
    
    st.latex(r"a = 2,\quad M = 2^2 \cdot 3 \cdot 5 = 60")
