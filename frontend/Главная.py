with st.expander("📐 Метод Ферма", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея.** Любое нечётное составное n можно представить в виде разности квадратов:
        """)
        st.latex(r"n = x^2 - y^2 = (x-y)(x+y)")
        st.markdown("""
Тогда делители: p = x − y, q = x + y.

**Шаги алгоритма:**
1. Начать с x = ⌈√n⌉
2. Вычислить w = x² − n
3. Если w — полный квадрат: y = √w, вернуть (x−y, x+y)
4. Иначе x ← x + 1, перейти к шагу 2

**Сложность:** O((q − p) / 2) итераций, где p, q — делители.
- Если p ≈ q (делители близки к √n) → мгновенно
- Если p ≪ q → катастрофически медленно

**Историческое значение:** прямой предшественник квадратичного решета.
        """)
    with c2:
        st.latex(r"w = x^2 - n \stackrel{?}{=} y^2")
        st.latex(r"p = x - y,\quad q = x + y")
        st.caption("Проверяем каждый x начиная с ⌈√n⌉")


with st.expander("🔄 ρ-метод Полларда (Rho)", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея.** Парадокс дней рождения: в случайной последовательности x₀, x₁, x₂, …
по модулю неизвестного делителя p цикл возникает примерно через O(√p) шагов.
Алгоритм Флойда обнаруживает цикл без хранения всей последовательности.

**Шаги алгоритма:**
1. Выбрать x = y = 2, c = 1, полином f(x) = (x² + c) mod n
2. На каждом шаге: x ← f(x), y ← f(f(y))  («черепаха и заяц»)
3. Вычислить d = НОД(|x − y|, n)
4. Если 1 < d < n → делитель найден
5. Если d = n → перезапустить с другим c

**Сложность:** O(n^{1/4}) операций, O(1) памяти.
        """)
        st.latex(r"x_{i+1} = f(x_i) = (x_i^2 + c)\bmod n")
    with c2:
        st.latex(r"\gcd(|x - y|,\; n)")
        st.latex(r"T \approx O(p^{1/2}) \approx O(n^{1/4})")
        st.caption("p — наименьший делитель n")

with st.expander("📉 (p−1)-метод Полларда", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея.** По Малой теореме Ферма: если p | n и (p−1) является B-гладким
(все простые множители ≤ B), то:
        """)
        st.latex(r"a^{M} \equiv 1 \pmod{p}, \quad M = \prod_{q \leq B} q^{\lfloor \log_q B \rfloor}")
        st.markdown("""
Значит p | НОД(a^M − 1, n).

**Шаги алгоритма:**
1. Выбрать a = 2, построить список простых до B
2. Для каждого простого q ≤ B: a ← a^(q^k) mod n, где q^k ≤ B
3. d = НОД(a − 1, n)
4. Если 1 < d < n → делитель найден
5. Иначе увеличить B и повторить

**Когда работает:** (p−1) содержит только малые простые.
**Когда не работает:** оба делителя имеют «жёсткое» (p−1).
        """)
    with c2:
        st.latex(r"a^{p-1} \equiv 1 \pmod{p}")
        st.latex(r"p \mid \gcd(a^M - 1,\; n)")
        st.caption("Малая теорема Ферма")

with st.expander("📈 (p+1)-метод Вильямса", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея.** Аналог (p−1)-метода, но использует последовательности Лукаса V_k(P, Q=1).
Работает, когда (p+1) является B-гладким.

**Последовательности Лукаса:**
        """)
        st.latex(r"V_0 = 2,\quad V_1 = P,\quad V_k = P\cdot V_{k-1} - V_{k-2}")
        st.markdown("""
**Ключевое свойство:** если p | n и (p+1) | M, то V_M ≡ 2 (mod p).

**Шаги алгоритма:**
1. Выбрать параметр P, построить список простых до B
2. Для каждого q ≤ B: V ← V_{q^k}(V, 1) mod n  (бинарный ladder-алгоритм)
3. d = НОД(V − 2, n)
4. Если 1 < d < n → делитель найден
5. Иначе сменить P или увеличить B

**Быстрое вычисление** (удвоение индекса):
        """)
        st.latex(r"V_{2k} = V_k^2 - 2 \pmod{n}")
        st.latex(r"V_{2k+1} = V_k \cdot V_{k+1} - P \pmod{n}")
    with c2:
        st.latex(r"p \mid \gcd(V_M - 2,\; n)")
        st.caption("(p+1) должно быть B-гладким")

with st.expander("🔷 SQUFOF — метод квадратичных форм Шенкса", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея.** В цикле редуцированных бинарных квадратичных форм с дискриминантом D = k·n
ищем «золотую» форму — такую, где Q является полным квадратом s² > 1.
Из неё обратным ходом извлекается делитель.

**Форма** (a, b, c): ax² + bxy + cy², дискриминант D = b² − 4ac.
Кодируется парой (P, Q).

**Рекуррентность (шаг редукции):**
        """)
        st.latex(r"q = \left\lfloor\frac{\lfloor\sqrt{D}\rfloor + P}{Q}\right\rfloor")
        st.latex(r"P' = q \cdot Q - P,\quad Q' = Q_{\text{prev}} + q(P - P')")
        st.markdown("""
**Шаги алгоритма:**
1. Фаза 1: итерировать редукцию, пока Q не станет полным квадратом s² (на чётном шаге)
2. Фаза 2: обратный ход из «золотой» формы до стабилизации P' = P
3. d = НОД(Q, n)

**Сложность:** O(n^{1/4}) по времени, O(1) по памяти.
Самый быстрый экспоненциальный алгоритм для чисел до ~60–70 бит.
        """)
    with c2:
        st.latex(r"D = k \cdot n")
        st.latex(r"Q_i = s^2 \Rightarrow \gcd(Q,\, n)")
        st.caption("Мультипликаторы k улучшают шансы нахождения золотой формы")

st.divider()

