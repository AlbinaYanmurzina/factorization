with st.expander("🔢 НОД — Наибольший общий делитель", expanded=False):
    st.markdown("""
**Определение:** НОД(a, b) — наибольшее натуральное число, которое делит и a, и b без остатка.

**Пример:** НОД(48, 18) = 6, так как 48 = 6·8, 18 = 6·3, и 6 — наибольшее такое число.

**Алгоритм Евклида** — эффективный метод нахождения НОД:
1. Делим большее число на меньшее с остатком
2. Заменяем большее число на меньшее, а меньшее — на остаток
3. Повторяем, пока остаток не станет равен 0
4. Последнее ненулевое число — это НОД

**Пример вычисления НОД(48, 18):**
- 48 = 2 · 18 + 12
- 18 = 1 · 12 + 6
- 12 = 2 · 6 + 0

НОД(48, 18) = 6

**Применение в факторизации:** Если НОД(a, n) > 1, то НОД(a, n) является делителем n.
    """)
    st.latex(r"\gcd(a, b) = \gcd(b, a \bmod b)")
