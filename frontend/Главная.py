st.subheader("Субэкспоненциальные алгоритмы")

with st.expander("⚙️ Квадратичное решето — базовый алгоритм (Диксона)", expanded=False):
    c1, c2 = st.columns([2, 1])
    with c1:
        st.markdown("""
**Идея Диксона.** Ищем x, y такие что x² ≡ y² (mod n).
Тогда НОД(x−y, n) с вероятностью 1/2 даёт нетривиальный делитель.

**Полином просеивания:**
        """)
        st.latex(r"Q(x) = x^2 - n, \quad x = \lceil\sqrt{n}\rceil, \lceil\sqrt{n}\rceil+1, \ldots")
        st.markdown("""
Q(x) мало по модулю (≈ 2x·Δ), поэтому шансы на гладкость высоки.

**Факторная база:** простые p ≤ B, для которых (n/p) = 1 (символ Лежандра).

**Шаги алгоритма:**
1. Выбрать B по формуле L-нотации: B ≈ exp(0.5·√(ln n · ln ln n))
2. Построить факторную базу FB
3. Перебирать x, проверять Q(x) на B-гладкость пробным делением
4. Набрать |FB| + 5 гладких чисел
5. Составить матрицу показателей степеней mod 2
6. Гаусс над GF(2) → зависимости → НОД(X−Y, n)

**Недостаток:** поиск гладких — пробным делением, O(M · |FB|).
        """)
    with c2:
        st.latex(r"B \approx \exp\!\left(0.5\sqrt{\ln n \cdot \ln\ln n}\right)")
        st.latex(r"\left(\frac{n}{p}\right) = 1")
        st.latex(r"Ax = 0 \pmod{2}")
        st.caption("Гаусс над GF(2) находит подмножество с квадратным произведением")

st.divider()

