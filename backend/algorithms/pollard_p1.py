"""
backend/algorithms/pollard_p1.py

(p-1)-метод Полларда

Метод факторизации, основанный на малой теореме Ферма.
Эффективен когда у делителя p число (p-1) является B-гладким.

B-гладкое число: число, все простые делители которого не превосходят B.
Например, 24 = 2³ × 3 является 3-гладким.

Малая теорема Ферма: если p простое и НОД(a, p) = 1, то a^(p-1) ≡ 1 (mod p)
"""

import math
from typing import List
from .base import FactorizationAlgorithm
from .math_utils import is_prime, generate_primes

class PollardP1(FactorizationAlgorithm):
    """
    (p-1)-метод Полларда для факторизации целых чисел.
    """
    
    def __init__(self):
        """Инициализация (p-1)-метода Полларда."""
        super().__init__()

    def _p1_step(self, n: int, B: int = 2000, base: int = 2) -> int:
        """
        Один проход (p-1)-метода с границей гладкости B.
        
        Алгоритм:
        1. Генерируем все простые p ≤ B
        2. Для каждого простого p находим максимальную степень p^k ≤ B
        3. Последовательно вычисляем a = a^(p^k) mod n
        4. После каждого шага проверяем d = НОД(a - 1, n)
        5. Если 1 < d < n - нашли делитель  

        n (int): Число для факторизации (n > 1)
        B (int): Граница гладкости (по умолчанию 2000)
        

        """
        # Генерируем все простые числа до B (факторная база)
        primes = generate_primes(B)

        self.log_step("Инициализация (p−1)-метода", {
            "message": (
                f"Число n = {n}, граница гладкости B = {B}\n"
                f"Идея: если p | n и (p−1) является B-гладким числом,\n"
                f"то по МТФ: a^(p−1) ≡ 1 (mod p), значит p | НОД(a^M − 1, n),\n"
                f"где M = НОК всех простых степеней ≤ B.\n"
                f"База a = 2. Простых в базе: {len(primes)} (до {primes[-1] if primes else '—'})"
            )
        })

        # Начальное значение базы (обычно a = 2)
        a = base % n
        base_gcd = math.gcd(a, n)
        if 1 < base_gcd < n:
            self.log_step("Делитель найден по базе", {
                "message": f"gcd({base}, {n}) = {base_gcd}. База сразу дала нетривиальный делитель."
            })
            return base_gcd
        # Таблица для логирования промежуточных результатов
        table_data = []
        # Логируем каждый 8-й шаг для читаемости
        log_interval = max(1, len(primes) // 8)

        # Обрабатываем каждое простое из факторной базы
        for idx, p in enumerate(primes):
            # Находим максимальную степень p^k ≤ B
            # Это нужно для вычисления M = НОК всех простых степеней ≤ B
            p_pow = p
            while p_pow * p <= B:
                p_pow *= p

            a_prev = a
            a = pow(a, p_pow, n)
            d = math.gcd(a - 1, n)

            if idx % log_interval == 0 or (1 < d < n):
                table_data.append({
                    "p": p,
                    "p^k ≤ B": p_pow,
                    "a = a^(p^k) mod n": str(a),
                    "НОД(a−1, n)": str(d)
                })

            if 1 < d < n:
                self.log_step("Промежуточные шаги", {
                    "message": (
                        f"На простом p={p} (степень p^k={p_pow}):\n"
                        f"a = {a_prev}^{p_pow} mod {n} = {a}\n"
                        f"НОД(a−1, n) = НОД({a}−1, {n}) = {d}\n"
                        f"Нетривиальный делитель найден!"
                    ),
                    "table": table_data
                })
                self.log_step("Найден делитель", {
                    "message": f"p−1 оказался B-гладким при B={B}. Делитель: {d}"
                })
                return d

        d = math.gcd(a - 1, n)
        if 1 < d < n:
            self.log_step("Успех на финальном шаге", {
                "message": f"НОД(a−1, n) = {d} после обработки всех простых до B={B}.",
                "table": table_data
            })
            return d

        self.log_step("Неудача при B=" + str(B), {
            "message": (
                f"НОД(a−1, n) = {d} — тривиальный результат.\n"
                f"Вероятная причина: (p−1) содержит простой множитель > B.\n"
                f"Решение: увеличить границу B и повторить."
            ),
            "table": table_data
        })
        return n

    def factorize(self, n: int) -> List[int]:
        """
        Полная факторизация числа n методом (p-1) Полларда.
        
        Рекурсивно применяет (p-1)-метод для разложения числа на простые множители.
        Использует стек для обработки найденных делителей.
        
        1. Проверка тривиальных случаев (n ≤ 1, чётные, простые)
        2. Пробное деление малыми простыми (2-100) для ускорения
        3. Последовательные попытки с B = 100, 1000, 10000
        4. Рекурсивная факторизация найденных делителей
        5. При неудаче возвращаем [n]

        """
        self.clear_logs()

        # Тривиальные случаи
        if n <= 1: return [n]
        if n == 2: return [2]
        if is_prime(n):
            self.log_step("Число простое", {"message": f"{n} — простое, факторизация тривиальна."})
            return [n]
        
        # Специальная обработка степеней двойки
        if n > 0 and (n & (n - 1)) == 0:
            # n является степенью двойки
            power = n.bit_length() - 1
            self.log_step("Степень двойки", {"message": f"{n} = 2^{power}"})
            return [2] * power
        
        self.log_step("Стратегия факторизации", {
            "message": (
                f"n = {n}\n"
                f"Факторизация — это нахождение простых чисел, произведение которых равно n.\n"
                f"Например: 15 = 3 × 5, 84 = 2 × 2 × 3 × 7.\n"
                f"(p−1)-метод Полларда работает, когда у делителя p число (p−1) раскладывается\n"
                f"только на малые простые — тогда его можно найти через теорему Ферма.\n\n"
                f"**Стратегия:** Пробуем с возрастающими границами B: 100 → 1000 → 10000\n"
                f"Это упрощённая реализация (только Stage 1). Если все попытки неудачны,\n"
                f"метод быстро определяет, что число не является B-гладким (~11,000 операций).\n"
                f"Это нормально: (p−1)-метод — специализированный алгоритм для гладких чисел."
            )
        })

        # Список для накопления найденных простых множителей
        factors = []
        # Стек для обработки оставшихся чисел
        stack = [n]
        
        # Последовательные попытки с увеличивающейся границей гладкости
        # Примечание: это упрощённая реализация, использующая только Stage 1
        # Классический двухэтапный алгоритм использует Stage 1 (один B₁) + Stage 2 (B₂ >> B₁)
        # Здесь мы делаем 3 независимых прохода Stage 1 с разными B
        # Если все попытки неудачны, метод быстро определяет негладкость (~11,000 операций)
        B_levels = [3, 5, 10, 25, 50, 100, 1000, 10000]
        bases = [2, 3, 5, 7, 11]
        
        # Обрабатываем числа из стека, пока он не опустеет
        while stack:
            current = stack.pop()
            
            # Тривиальный случай: чётное число
            if current % 2 == 0:
                self.log_step("Тривиальный делитель", {"message": f"{current} чётное → делитель 2"})
                stack.append(2)
                stack.append(current // 2)
                continue
                
            # Если число простое — сразу добавляем в результат
            if is_prime(current):
                factors.append(current)
                self.log_step("Простое число найдено", {
                    "message": f"{current} — простое (тест Миллера–Рабина). Добавляем в результат."
                })
                continue
            
            self.log_step("Составное число", {
                "message": f"{current} — составное. Запускаем (p−1)-шаг для поиска делителя."
            })
            
            # Пытаемся найти делитель с разными значениями B
            divisor = None
            for B in B_levels:
                for base in bases:
                    self.log_step(f"Попытка с B = {B}, a = {base}", {
                        "message": f"Запускаем (p−1)-шаг с границей B={B} и базой a={base} для числа {current}."
                    })
                    
                    divisor = self._p1_step(current, B, base)
                    
                    # Если нашли нетривиальный делитель
                    if divisor != current:
                        quotient = current // divisor
                        self.log_step("Разбиение числа", {
                            "message": (
                                f"{current} = {divisor} × {quotient}\n"
                                f"Оба числа отправляются на дальнейшую проверку."
                            )
                        })
                        stack.append(divisor)
                        stack.append(quotient)
                        break
                if divisor != current:
                    break
            
            # Если все попытки неудачны
            if divisor == current:
                self.log_step("Алгоритм не справился", {
                    "message": (
                        f"Ни при одной паре параметров B и a делитель не найден для {current}.\n"
                        f"Вероятно, оба простых множителя имеют негладкое (p−1).\n"
                        f"Это нормально: (p−1)-метод — специализированный алгоритм для гладких чисел.\n"
                        f"Метод быстро определил негладкость в пределах выбранных B и не тратит время впустую.\n"
                        f"Для таких чисел лучше использовать универсальные методы (ρ-метод, Диксон).\n"
                        f"Добавляем число как есть (возможно составное)."
                    )
                })
                factors.append(current)

        # Сортируем множители по возрастанию для удобного отображения
        factors.sort()
        self.log_step("Факторизация завершена", {
            "message": f"Итоговое разложение: {n} = {' × '.join(map(str, factors))}"
        })

        return factors
