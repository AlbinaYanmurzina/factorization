"""
backend/algorithms/pollard_p1.py

(p-1)-метод Полларда (раздел 3.2 учебного пособия).

Метод факторизации, основанный на малой теореме Ферма.
Эффективен когда у делителя p число (p-1) является B-гладким.

B-гладкое число: число, все простые делители которого не превосходят B.
Например, 24 = 2³ × 3 является 3-гладким.

Теоретическая основа:
Малая теорема Ферма: если p простое и НОД(a, p) = 1, то a^(p-1) ≡ 1 (mod p)

Идея алгоритма:
Если p | n и (p-1) является B-гладким, то (p-1) | M, где
M = НОК всех простых степеней ≤ B.
Тогда a^M ≡ 1 (mod p), значит p | НОД(a^M - 1, n).

Сложность: O(B log B log² n)
Память: O(π(B)), где π(B) - количество простых до B

Применимость:
- Эффективен для чисел, у которых (p-1) имеет только малые простые делители
- Дополняет ρ-метод Полларда (работает в других случаях)
- Часто используется в комбинации с другими методами
"""

import math
from typing import List
from .base import FactorizationAlgorithm
from .math_utils import is_prime, generate_primes

class PollardP1(FactorizationAlgorithm):
    """
    (p-1)-метод Полларда для факторизации целых чисел.
    
    Attributes:
        steps_log: Лог шагов работы алгоритма (наследуется от базового класса)
    """
    
    def __init__(self):
        """Инициализация (p-1)-метода Полларда."""
        super().__init__()

    def _p1_step(self, n: int, B: int = 2000) -> int:
        """
        Один проход (p-1)-метода с границей гладкости B.
        
        Алгоритм:
        1. Генерируем все простые p ≤ B
        2. Для каждого простого p находим максимальную степень p^k ≤ B
        3. Последовательно вычисляем a = a^(p^k) mod n
        4. После каждого шага проверяем d = НОД(a - 1, n)
        5. Если 1 < d < n - нашли делитель
        
        Args:
            n (int): Число для факторизации (n > 1)
            B (int): Граница гладкости (по умолчанию 2000)
        
        Returns:
            int: Нетривиальный делитель n, или n если делитель не найден
        
        Примечание:
            Метод работает когда у делителя p число (p-1) раскладывается
            только на простые ≤ B. Если B слишком мал, метод не найдёт делитель.
        """
        # Генерируем все простые числа до B (факторная база)
        primes = generate_primes(B)

        self.log_step("Инициализация (p−1)-метода", {
            "message": (
                f"Число n = {n}, граница гладкости B = {B}\n"
                f"Идея: если p | n и (p−1) является B-гладким числом,\n"
                f"то по МТФ: a^(p−1) ≡ 1 (mod p), значит p | НОД(a^M − 1, n),\n"
                f"где M = НОК всех простых степеней ≤ B.\n"
                f"База a = 2. Простых в базе: {len(primes)} (до {primes[-1] if primes else '—'})"
            )
        })

        # Начальное значение базы (обычно a = 2)
        a = 2
        # Таблица для логирования промежуточных результатов
        table_data = []
        # Логируем каждый 8-й шаг для читаемости
        log_interval = max(1, len(primes) // 8)

        # Обрабатываем каждое простое из факторной базы
        for idx, p in enumerate(primes):
            # Находим максимальную степень p^k ≤ B
            # Это нужно для вычисления M = НОК всех простых степеней ≤ B
            p_pow = p
            while p_pow * p <= B:
                p_pow *= p

            a_prev = a
            a = pow(a, p_pow, n)
            d = math.gcd(a - 1, n)

            if idx % log_interval == 0 or (1 < d < n):
                table_data.append({
                    "p": p,
                    "p^k ≤ B": p_pow,
                    "a = a^(p^k) mod n": a,
                    "НОД(a−1, n)": d
                })

            if 1 < d < n:
                self.log_step("Промежуточные шаги", {
                    "message": (
                        f"На простом p={p} (степень p^k={p_pow}):\n"
                        f"a = {a_prev}^{p_pow} mod {n} = {a}\n"
                        f"НОД(a−1, n) = НОД({a}−1, {n}) = {d}\n"
                        f"Нетривиальный делитель найден!"
                    ),
                    "table": table_data
                })
                self.log_step("Найден делитель", {
                    "message": f"p−1 оказался B-гладким при B={B}. Делитель: {d}"
                })
                return d

        d = math.gcd(a - 1, n)
        if 1 < d < n:
            self.log_step("Успех на финальном шаге", {
                "message": f"НОД(a−1, n) = {d} после обработки всех простых до B={B}.",
                "table": table_data
            })
            return d

        self.log_step("Неудача при B=" + str(B), {
            "message": (
                f"НОД(a−1, n) = {d} — тривиальный результат.\n"
                f"Вероятная причина: (p−1) содержит простой множитель > B.\n"
                f"Решение: увеличить границу B и повторить."
            ),
            "table": table_data
        })
        return n

    def factorize(self, n: int) -> List[int]:
        """
        Полная факторизация числа n методом (p-1) Полларда.
        
        Пытается найти делитель n, используя (p-1)-метод с различными
        границами гладкости B. Если делитель найден, возвращает разложение.
        
        Стратегия:
        1. Проверка тривиальных случаев (n ≤ 1, чётные, простые)
        2. Последовательные попытки с B = 100, 1000, 10000
        3. При успехе возвращаем [p, q] где n = p × q
        4. При неудаче возвращаем [n]
        
        Args:
            n (int): Число для факторизации (n > 0)
        
        Returns:
            List[int]: Список из двух делителей [p, q] или [n] при неудаче
        
        Примеры:
            factorize(143) → [11, 13]  # 11-1 = 10 = 2×5 (5-гладкое)
            factorize(221) → [13, 17]  # 13-1 = 12 = 2²×3 (3-гладкое)
            factorize(1000003) → [1000003]  # простое число
        
        Примечание:
            Метод эффективен только когда (p-1) является B-гладким для
            некоторого разумного B. Для чисел с большими простыми делителями
            в (p-1) метод не найдёт делитель.
            
            Дополняет ρ-метод Полларда: работает в разных случаях.
        """
        self.clear_logs()

        # Тривиальные случаи
        if n <= 1: return [n]
        if n % 2 == 0:
            self.log_step("Тривиальный делитель", {"message": f"{n} чётное → делитель 2"})
            return [2, n // 2]
        if is_prime(n):
            self.log_step("Число простое", {"message": f"{n} — простое, факторизация тривиальна."})
            return [n]

        self.log_step("Стратегия факторизации", {
            "message": (
                f"n = {n}\n"
                f"Факторизация — это нахождение простых чисел, произведение которых равно n.\n"
                f"Например: 15 = 3 × 5, 84 = 2 × 2 × 3 × 7.\n"
                f"(p−1)-метод Полларда работает, когда у делителя p число (p−1) раскладывается\n"
                f"только на малые простые — тогда его можно найти через теорему Ферма.\n"
                f"Пробуем с возрастающими границами B: 100 → 1000 → 10000"
            )
        })

        # Последовательные попытки с увеличивающейся границей гладкости
        B_levels = [100, 1000, 10000]
        
        for B in B_levels:
            self.log_step(f"Попытка с B = {B}", {
                "message": f"Запускаем (p−1)-шаг с границей B={B}."
            })
            divisor = self._p1_step(n, B)
            
            # Если нашли нетривиальный делитель
            if divisor != n:
                factors = sorted([divisor, n // divisor])
                self.log_step("Факторизация завершена", {
                    "message": f"{n} = {factors[0]} × {factors[1]}"
                })
                return factors

        # Все попытки неудачны
        self.log_step("Алгоритм не справился", {
            "message": (
                f"Ни при одном B делитель не найден.\n"
                f"Вероятно, оба простых множителя имеют негладкое (p−1).\n"
                f"Рекомендуется использовать ρ-метод или квадратичное решето."
            )
        })
        return [n]
